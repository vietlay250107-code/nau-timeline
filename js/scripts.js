function fileNameFromTitle(title) {
  return title.toLowerCase()
    .replace(/đ/g, "d")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[,:]/g, "")
    .trim()
    .replace(/\s+/g, "-")
    .replace(/[^a-z0-9-]/g, "")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "") + ".jpg";
}

function wrapCanvasText(context, text, maxWidth) {
  const lines = [];

  for (const paragraph of text.split(/\r?\n/)) {
    if (!paragraph.trim()) {
      lines.push("");
      continue;
    }

    let line = "";

    for (const word of paragraph.trim().split(/\s+/)) {
      const candidate = line ? `${line} ${word}` : word;
      if (context.measureText(candidate).width <= maxWidth) {
        line = candidate;
        continue;
      }

      if (line) {
        lines.push(line);
        line = "";
      }

      if (context.measureText(word).width <= maxWidth) {
        line = word;
        continue;
      }

      let part = "";
      for (const character of word) {
        if (part && context.measureText(part + character).width > maxWidth) {
          lines.push(part);
          part = character;
        } else {
          part += character;
        }
      }
      line = part;
    }

    lines.push(line);
  }

  return lines;
}

async function loadNotoSans() {
  if (!document.fonts || typeof document.fonts.load !== "function") {
    throw new Error("Không tải được phông Noto Sans.");
  }

  const sample = "Tên mốc giờ ghi chú";
  const [regular, bold] = await Promise.all([
    document.fonts.load('400 32px "Noto Sans"', sample),
    document.fonts.load('700 32px "Noto Sans"', sample)
  ]);
  await document.fonts.ready;

  if (!regular.length || !bold.length || [...regular, ...bold].some((face) => face.status !== "loaded")) {
    throw new Error("Không tải được phông Noto Sans.");
  }
}

function loadSourceImage(src) {
  return new Promise((resolve, reject) => {
    const image = new Image();
    image.onload = () => resolve(image);
    image.onerror = () => reject(new Error("Không tải được ảnh gốc."));
    image.src = src;
  });
}

function drawLines(context, lines, x, y, lineHeight) {
  for (const line of lines) {
    if (line) context.fillText(line, x, y);
    y += lineHeight;
  }
  return y;
}

async function createDownload(photo, name, note) {
  const [image] = await Promise.all([loadSourceImage(photo.src), loadNotoSans()]);
  const width = image.naturalWidth;
  const imageHeight = image.naturalHeight;
  const paddingX = Math.round(width * 0.05);
  const paddingY = Math.round(width * 0.04);
  const maxTextWidth = width - paddingX * 2;
  const fontSize = Math.min(56, Math.max(32, Math.round(width * 0.032)));
  const timeFontSize = Math.round(fontSize * 1.18);
  const lineHeight = Math.round(fontSize * 1.42);
  const timeLineHeight = Math.round(timeFontSize * 1.42);
  const gap = Math.round(fontSize * 0.55);
  const measuringCanvas = document.createElement("canvas");
  const measuringContext = measuringCanvas.getContext("2d");
  if (!measuringContext) throw new Error("Không thể tạo ảnh.");

  measuringContext.font = `700 ${fontSize}px "Noto Sans"`;
  const nameLines = name ? wrapCanvasText(measuringContext, name, maxTextWidth) : [];
  measuringContext.font = `400 ${fontSize}px "Noto Sans"`;
  const noteLines = note ? wrapCanvasText(measuringContext, note, maxTextWidth) : [];
  const bandHeight = paddingY * 2 + nameLines.length * lineHeight + (nameLines.length ? gap : 0) + timeLineHeight + (noteLines.length ? gap + noteLines.length * lineHeight : 0);
  const canvas = document.createElement("canvas");
  canvas.width = width;
  canvas.height = imageHeight + bandHeight;
  const context = canvas.getContext("2d");
  if (!context) throw new Error("Không thể tạo ảnh.");

  context.fillStyle = "#ffffff";
  context.fillRect(0, 0, canvas.width, canvas.height);
  context.drawImage(image, 0, 0, width, imageHeight);
  context.textBaseline = "top";
  let y = imageHeight + paddingY;

  if (nameLines.length) {
    context.font = `700 ${fontSize}px "Noto Sans"`;
    context.fillStyle = "#172435";
    y = drawLines(context, nameLines, paddingX, y, lineHeight) + gap;
  }

  context.font = `700 ${timeFontSize}px "Noto Sans"`;
  context.fillStyle = "#003FA6";
  context.fillText(photo.time, paddingX, y);
  y += timeLineHeight;

  if (noteLines.length) {
    context.font = `400 ${fontSize}px "Noto Sans"`;
    context.fillStyle = "#586574";
    drawLines(context, noteLines, paddingX, y + gap, lineHeight);
  }

  const blob = await new Promise((resolve, reject) => {
    canvas.toBlob((result) => result ? resolve(result) : reject(new Error("Không thể xuất ảnh JPEG.")), "image/jpeg", 0.95);
  });
  const downloadUrl = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = downloadUrl;
  link.download = fileNameFromTitle(eventData[photo.folder + "-" + photo.number].title);
  document.body.append(link);
  link.click();
  link.remove();
  window.setTimeout(() => URL.revokeObjectURL(downloadUrl), 3000);
}

