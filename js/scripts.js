function setupMobileMenu() {
  const menu = document.querySelector(".mobile-menu");
  if (!menu) return;

  const button = menu.querySelector(".mobile-menu-toggle");
  const panel = menu.querySelector(".mobile-menu-panel");
  if (!button || !panel) return;

  const setOpen = (open) => {
    menu.classList.toggle("is-open", open);
    button.setAttribute("aria-expanded", String(open));
    button.setAttribute("aria-label", open ? "Đóng menu" : "Mở menu");
  };

  button.addEventListener("click", () => setOpen(!menu.classList.contains("is-open")));
  panel.querySelectorAll("a").forEach((link) => {
    link.addEventListener("click", () => setOpen(false));
  });
}

function setupTimeline() {
  const timeSelect = document.querySelector("#time-select");
  const photoSelect = document.querySelector("#photo-select");
  if (!timeSelect || !photoSelect) return;

  const cards = Array.from(document.querySelectorAll(".photo-card[data-time][data-photo-id]"));
  cards.forEach((card) => {
    const title = eventData[card.dataset.photoId]?.title;
    const label = card.querySelector(".photo-card__event");
    const image = card.querySelector("img");
    if (label && title) label.textContent = title;
    if (image && title) image.alt = title;
    if (card.tagName === "A" && title) {
      card.href = detailHref(card.dataset.photoId);
      card.setAttribute("aria-label", `Xem chi tiết: ${title}`);
    }
  });
  const groups = Array.from(document.querySelectorAll(".time-group"));
  const saveButton = document.querySelector("#save-image");
  const shareButton = document.querySelector("#share-image");
  const errorElement = document.querySelector("#save-error");

  const selectedPhoto = () => {
    const photo = getPhotoData(photoSelect.value);
    return photo && photo.folder === timeSelect.value ? photo : null;
  };

  const setError = (message) => {
    if (!errorElement) {
      if (message) window.alert(message);
      return;
    }
    errorElement.textContent = message;
    errorElement.hidden = !message;
  };

  const requiredPhoto = () => {
    const photo = selectedPhoto();
    if (!photo) setError("Vui lòng chọn mốc giờ và ảnh.");
    return photo;
  };

  const fadePhotos = (visibleCards) => {
    if (prefersReducedMotion()) return;
    const images = visibleCards.map((card) => card.querySelector("img")).filter(Boolean);
    images.forEach((image) => image.classList.remove("selection-fade"));
    void document.body.offsetWidth;
    images.forEach((image) => image.classList.add("selection-fade"));
  };

  const updateVisiblePhotos = (animate = false) => {
    const photo = selectedPhoto();
    const chosenCard = photo ? cards.find((card) => card.dataset.photoId === photoSelect.value) : null;
    cards.forEach((card) => {
      card.parentElement.hidden = Boolean(chosenCard) && card !== chosenCard;
    });
    groups.forEach((group) => {
      group.hidden = Boolean(chosenCard) && !group.contains(chosenCard);
    });
    if (animate) fadePhotos(chosenCard ? [chosenCard] : cards);
  };

  timeSelect.addEventListener("change", () => {
    photoSelect.replaceChildren(new Option("Chọn ảnh", ""));
    photoSelect.disabled = !timeSelect.value;
    cards.filter((card) => card.dataset.time === timeSelect.value).forEach((card) => {
      const photo = getPhotoData(card.dataset.photoId);
      if (photo) photoSelect.add(new Option("Ảnh " + photo.number, card.dataset.photoId));
    });
    updateVisiblePhotos(true);
  });

  photoSelect.addEventListener("change", () => updateVisiblePhotos(true));
  updateVisiblePhotos();

  if (saveButton) {
    saveButton.addEventListener("click", async () => {
      setError("");
      const photo = requiredPhoto();
      if (!photo) return;

      const name = (document.querySelector("#visitor-name")?.value || "").trim().slice(0, 60);
      const note = (document.querySelector("#visitor-note")?.value || "").trim().slice(0, 300);
      saveButton.disabled = true;
      try {
        await createDownload(photo, name, note);
      } catch (error) {
        setError(error instanceof Error ? error.message : "Không thể tạo ảnh.");
      } finally {
        saveButton.disabled = false;
      }
    });
  }

  if (shareButton) {
    shareButton.addEventListener("click", async () => {
      setError("");
      if (!requiredPhoto()) return;

      const href = new URL(detailHref(photoSelect.value), window.location.href).href;
      try {
        if (typeof navigator.clipboard?.writeText !== "function") throw new Error("Clipboard unavailable");
        await navigator.clipboard.writeText(href);
      } catch {
        window.location.assign(href);
        return;
      }
      window.alert("Đã sao chép liên kết");
    });
  }
}

function setupDetail() {
  const image = document.querySelector("#detail-image");
  if (!image) return;

  const backLink = document.querySelector(".back-link");
  backLink?.addEventListener("click", (event) => {
    if (event.defaultPrevented || event.button !== 0 || event.ctrlKey || event.shiftKey || event.altKey || event.metaKey) return;

    let referrer;
    try {
      referrer = new URL(document.referrer);
    } catch {
      return;
    }
    if (referrer.origin !== window.location.origin || referrer.pathname === window.location.pathname) return;

    event.preventDefault();
    window.history.back();
  });

  const id = new URLSearchParams(window.location.search).get("id");
  const photo = getPhotoData(id);
  const event = photo ? eventData[id] : null;
  const dimensions = photoDimensions[id];
  const time = document.querySelector("#detail-time");
  const title = document.querySelector("#detail-title");
  const intro = document.querySelector("#detail-intro");

  if (!photo || !event || !dimensions) {
    image.hidden = true;
    if (image.parentElement) image.parentElement.hidden = true;
    if (time) time.hidden = true;
    if (title) title.textContent = "Không tìm thấy ảnh.";
    if (intro) intro.hidden = true;
    return;
  }

  image.width = dimensions[0];
  image.height = dimensions[1];
  image.src = photo.src;
  image.alt = event.title;
  image.hidden = false;
  if (image.parentElement) image.parentElement.hidden = false;
  if (time) time.hidden = false;
  if (intro) intro.hidden = false;
  if (time) time.textContent = photo.time;
  if (title) title.textContent = event.title;
  if (intro) intro.textContent = event.intro;
}

function setupFeatured() {
  const cards = Array.from(document.querySelectorAll(".featured-card"));
  if (cards.length !== 6) return;

  const ids = Object.keys(eventData).filter((id) => id !== "1200-01");
  for (let i = ids.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [ids[i], ids[j]] = [ids[j], ids[i]];
  }

  ids.slice(0, 6).forEach((id, index) => {
    const photo = getPhotoData(id);
    const image = cards[index].querySelector("img");
    const title = cards[index].querySelector(".featured-card__title");
    if (!photo || !image || !title) return;

    cards[index].href = detailHref(id);
    image.src = photo.src;
    image.alt = eventData[id].title;
    title.textContent = eventData[id].title;
  });
}

function setupContact() {
  document.querySelectorAll(".site-footer [data-contact]").forEach((placeholder) => {
    const kind = placeholder.dataset.contact;
    const value = contactData[kind];
    if (!value) return;

    if (typeof value !== "string") {
      if (placeholder.tagName !== "A") return;
      placeholder.href = value.href;
      placeholder.setAttribute("aria-label", value.ariaLabel);
      placeholder.target = "_blank";
      placeholder.rel = "noopener noreferrer";
      placeholder.classList.remove("footer-placeholder");
      const label = placeholder.querySelector("span");
      if (label) label.textContent = value.label;
      return;
    }

    const link = document.createElement("a");
    link.className = "footer-link";
    link.href = kind === "hotline" ? `tel:+84${value.slice(1)}` : `mailto:${value}`;
    link.setAttribute("aria-label", kind === "hotline" ? `Gọi hotline ${value}` : `Gửi email tới ${value}`);
    link.replaceChildren(...placeholder.childNodes);
    const text = link.querySelector("span");
    if (text) text.textContent = value;
    placeholder.replaceWith(link);
  });

  document.addEventListener("click", (event) => {
    const link = event.target instanceof Element ? event.target.closest('a.footer-placeholder[href="#"]') : null;
    if (link) event.preventDefault();
  });
}

function setupReveal() {
  if (prefersReducedMotion() || !("IntersectionObserver" in window)) return;

  const observer = new IntersectionObserver((entries, currentObserver) => {
    entries.forEach((entry) => {
      if (!entry.isIntersecting) return;
      entry.target.classList.add("reveal-once");
      currentObserver.unobserve(entry.target);
    });
  }, { threshold: 0.1 });

  document.querySelectorAll(".content-panel, .creator-panel, .time-group h2, .photo-card, .detail-image-wrap, .detail-copy, .reveal-target").forEach((element) => {
    observer.observe(element);
  });
}

function setupPageTransitions() {
  window.addEventListener("pageshow", (event) => {
    if (!event.persisted) return;
    document.body.style.animation = "none";
    document.body.style.transition = "none";
    document.body.classList.remove("page-leaving");
    void document.body.offsetWidth;
    document.body.style.removeProperty("transition");
  });

  document.addEventListener("click", (event) => {
    if (event.defaultPrevented || event.button !== 0 || event.metaKey || event.ctrlKey || event.shiftKey || event.altKey || prefersReducedMotion()) return;

    const link = event.target instanceof Element ? event.target.closest("a[href]") : null;
    if (!link || link.hasAttribute("download") || (link.target && link.target !== "_self")) return;
    if (link.matches(".back-link")) return;

    const destination = new URL(link.href, window.location.href);
    if (destination.protocol !== window.location.protocol || destination.origin !== window.location.origin) return;
    if (destination.href === window.location.href) return;
    if (destination.pathname === window.location.pathname && destination.search === window.location.search && destination.hash) return;

    event.preventDefault();
    document.body.classList.add("page-leaving");
    window.setTimeout(() => window.location.assign(destination.href), 250);
  });
}

